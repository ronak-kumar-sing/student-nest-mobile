/**
 * Firebase Auth setup and helpers.
 *
 * Firebase JS SDK, auth only.
 * Initializes lazily on first access so mock mode never requires Firebase config.
 */

import { initializeApp, getApps, type FirebaseApp } from 'firebase/app';
import {
  initializeAuth,
  getAuth,
  getReactNativePersistence,
  connectAuthEmulator,
  signInWithCustomToken,
  signOut,
  onAuthStateChanged,
  type User,
  type Auth,
  type UserCredential,
} from 'firebase/auth';
import AsyncStorage from '@react-native-async-storage/async-storage';

export type { User, Auth, UserCredential };

let authInstance: Auth | null = null;
let emulatorConnected = false;

/**
 * Lazy initializer for Firebase Auth.
 * Reads config from environment variables:
 * - `EXPO_PUBLIC_FIREBASE_API_KEY`
 * - `EXPO_PUBLIC_FIREBASE_PROJECT_ID`
 * - `EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN` (default: `${projectId}.firebaseapp.com`)
 * - `EXPO_PUBLIC_FIREBASE_APP_ID` (optional)
 * - `EXPO_PUBLIC_FIREBASE_AUTH_EMULATOR_HOST` (e.g. localhost:9099 or 10.0.2.2:9099)
 */
export function getFirebaseAuth(): Auth {
  if (authInstance) {
    return authInstance;
  }

  const apiKey = process.env.EXPO_PUBLIC_FIREBASE_API_KEY;
  const projectId = process.env.EXPO_PUBLIC_FIREBASE_PROJECT_ID;

  if (!apiKey || !projectId) {
    throw new Error(
      'Firebase configuration missing. Please ensure EXPO_PUBLIC_FIREBASE_API_KEY and EXPO_PUBLIC_FIREBASE_PROJECT_ID are set.',
    );
  }

  const authDomain = process.env.EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN ?? `${projectId}.firebaseapp.com`;
  const appId = process.env.EXPO_PUBLIC_FIREBASE_APP_ID;

  const firebaseConfig = {
    apiKey,
    projectId,
    authDomain,
    ...(appId ? { appId } : {}),
  };

  let app: FirebaseApp;
  const apps = getApps();
  if (apps.length > 0 && apps[0]) {
    app = apps[0];
  } else {
    app = initializeApp(firebaseConfig);
  }

  let auth: Auth;
  try {
    auth = initializeAuth(app, {
      persistence: getReactNativePersistence(AsyncStorage),
    });
  } catch {
    auth = getAuth(app);
  }

  const emulatorHost = process.env.EXPO_PUBLIC_FIREBASE_AUTH_EMULATOR_HOST;
  if (emulatorHost && !emulatorConnected) {
    try {
      connectAuthEmulator(auth, `http://${emulatorHost}`, { disableWarnings: true });
    } catch {
      // In case the emulator was already connected on Fast Refresh
    }
    emulatorConnected = true;
  }

  authInstance = auth;
  return authInstance;
}

/**
 * Get the current user's ID token, or null if unauthenticated.
 * Awaits auth.authStateReady() so async persistence restores before reading currentUser.
 * @param forceRefresh - Whether to force a token refresh
 */
export async function getCurrentIdToken(forceRefresh = false): Promise<string | null> {
  const auth = getFirebaseAuth();
  await auth.authStateReady();
  const user = auth.currentUser;
  if (!user) {
    return null;
  }
  return user.getIdToken(forceRefresh);
}

/**
 * Sign in using a custom Firebase Auth token generated by the backend.
 */
export async function signInWithFirebaseCustomToken(token: string): Promise<UserCredential> {
  const auth = getFirebaseAuth();
  return signInWithCustomToken(auth, token);
}

/**
 * Sign out of Firebase Auth.
 */
export async function signOutFirebase(): Promise<void> {
  const auth = getFirebaseAuth();
  return signOut(auth);
}

/**
 * Subscribe to auth state changes. Returns an unsubscribe callback.
 */
export function subscribeToAuthState(cb: (user: User | null) => void): () => void {
  const auth = getFirebaseAuth();
  return onAuthStateChanged(auth, cb);
}

/**
 * Read the user's role custom claim ('student' | 'owner' | 'admin' | null) from their ID token.
 * Awaits auth.authStateReady() before reading currentUser.
 */
export async function getIdTokenRole(): Promise<'student' | 'owner' | 'admin' | null> {
  const auth = getFirebaseAuth();
  await auth.authStateReady();
  const user = auth.currentUser;
  if (!user) {
    return null;
  }
  const tokenResult = await user.getIdTokenResult();
  const role = tokenResult.claims['role'];
  if (role === 'student' || role === 'owner' || role === 'admin') {
    return role;
  }
  return null;
}
